    private fun set(code: Int, b0: Int, b1: Int, b2: Int, b3: Int, b4: Int) {
        val idx = code - 32
        if (idx in GLYPHS.indices) {
            GLYPHS[idx] = byteArrayOf(b0.toByte(), b1.toByte(), b2.toByte(), b3.toByte(), b4.toByte())
        }
    }

    fun stringWidth(text: String, scale: Float = 1.7f): Int {
        return Math.round(text.length * 6f * scale)
    }

    fun drawString(g: Graphics2D, text: String, x: Int, y: Int, color: Color, scale: Float = 1.7f) {
        g.color = color
        var curX = x
        val pw = Math.max(1, Math.round(scale))
        val ph = Math.max(1, Math.round(scale))
        for (i in 0 until text.length) {
            val ch = text[i]
            val idx = ch.code - 32
            if (idx !in GLYPHS.indices) {
                curX += Math.round(6f * scale)
                continue
            }
            val cols = GLYPHS[idx]
            for (col in 0 until 5) {
                val b = cols[col].toInt() and 0xFF
                val px = curX + Math.round(col * scale)
                for (row in 0 until 7) {
                    if ((b and (1 shl row)) != 0) {
                        val py = y - Math.round(11f * scale / 1.6f) + Math.round(row * scale)
                        g.fillRect(px, py, pw, ph)
                    }
                }
            }
            curX += Math.round(6f * scale)
        }
    }
